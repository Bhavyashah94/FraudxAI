def test_factual_counterfactual_always_populated_for_fraud():
    """Invariant 1: Every fraud transaction generated by DiscreteEventEngine carries factual_counterfactual."""
    engine = DiscreteEventEngine(
        n_cards=100,
        n_merchants=30,
        region="US",
        seed=42,
    )
    records = engine.generate_batch(n_transactions=500, fraud_prevalence=0.08)
    fraud_recs = [r for r in records if r.get("is_fraud") == 1]
    assert len(fraud_recs) >= 20, "Insufficient fraud records generated"

    for r in fraud_recs:
        assert "counterfactual_twin" in r, "Fraud transaction missing counterfactual_twin"
        assert "normative_baseline" in r, "Fraud transaction missing normative_baseline"
        twin = r["counterfactual_twin"]
        assert "amount" in twin, "Twin missing baseline amount"
        assert "channel_type" in twin or "pos_entry_mode" in twin, "Twin missing baseline channel"
        # Counterfactual mode must be TRANSACTIONAL_MUTATION or ADVERSARIAL_INSERTION
        assert r.get("counterfactual_mode") in ("TRANSACTIONAL_MUTATION", "ADVERSARIAL_INSERTION")


def test_ground_truth_phi_star_matches_canonical_interventions():
    """Invariant 2: Normalized intervention attribution phi* is positive only on active attack levers."""
    harness = XAIBenchmarkHarness(n_transactions=1000, fraud_prevalence=0.05, seed=42)
    _, _, _, records = harness.generate_and_prepare_dataset()
    fraud_recs = [r for r in records if r.get("is_fraud") == 1]
    assert len(fraud_recs) >= 20

    for r in fraud_recs:
        phi_interv = harness._build_interventional_ground_truth(r)
        tag = str(r.get("scenario_tag", ""))
        target_set = CANONICAL_ATTACK_INTERVENTIONS.get(tag)
        if not target_set:
            for canonical_tag, feats in CANONICAL_ATTACK_INTERVENTIONS.items():
                if canonical_tag in tag or tag in canonical_tag:
                    target_set = feats
                    break

        if not target_set:
            continue

        # Invariant: sum of normalized vector is 1.0 (or 0 if empty)
        assert np.isclose(np.sum(phi_interv), 1.0, atol=1e-5), "Intervention ground truth must normalize to 1.0"

        # Invariant: features outside canonical target set must have 0 attribution
        for j, feat in enumerate(FEATURE_NAMES):
            if feat not in target_set:
                assert phi_interv[j] == 0.0, f"Feature {feat} outside target set {target_set} has attribution {phi_interv[j]}"


def test_intervention_precision_and_recall_computation():
    """Invariant 3: Intervention Precision@k and Recall@k are mathematically bounded in [0.0, 1.0]."""
